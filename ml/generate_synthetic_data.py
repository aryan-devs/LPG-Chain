"""
generate_synthetic_data.py
--------------------------
Reproducible synthetic LPG cylinder booking history generator.

DISCLAIMER:
All data generated by this script is strictly SYNTHETIC and SIMULATED.
It does NOT represent real customer accounts, actual transactions, or measured
commercial LPG demand. This simulated dataset is used exclusively for initial
AI/ML model bootstrapping and cold-start demand forecasting demonstration.

Configurable Assumptions & Distributions:
- Time Horizon: 365 days (2025-10-01 to 2026-09-30)
- Random Seed: 42 (fully reproducible)
- Customer Pool: 800 pseudonymous household & commercial accounts
- Cylinder Categories:
    * DOMESTIC_14_2: ~75% volume, typical household refilling every 28-45 days.
    * DOMESTIC_5_0: ~15% volume, small households/students refilling every 35-60 days.
    * COMMERCIAL_19_0: ~10% volume, businesses/eateries refilling 3-8 cylinders weekly.
- Seasonality & Calendar Effects:
    * Domestic weekend boost: Saturday (+25%), Sunday (+30%)
    * Commercial weekday peak: Tuesday/Wednesday (+20%)
    * Winter heating/cooking spike: Nov-Feb (+20% domestic volume)
    * Festival/holiday surges: simulated festive period spikes
"""

import os
import random
import csv
from datetime import datetime, timedelta

RANDOM_SEED = 42
random.seed(RANDOM_SEED)

OUTPUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
OUTPUT_FILE = os.path.join(OUTPUT_DIR, "synthetic_bookings.csv")

CATEGORIES = {
    "DOMESTIC_14_2": {"capacity_kg": 14.2, "weight": 0.74, "avg_qty": 1, "interval_mean": 35},
    "DOMESTIC_5_0": {"capacity_kg": 5.0, "weight": 0.16, "avg_qty": 1, "interval_mean": 42},
    "COMMERCIAL_19_0": {"capacity_kg": 19.0, "weight": 0.10, "avg_qty": 4, "interval_mean": 7},
}

START_DATE = datetime(2025, 10, 1)
TOTAL_DAYS = 365
NUM_CUSTOMERS = 800

def get_season(month: int) -> str:
    if month in (11, 12, 1, 2):
        return "WINTER"
    elif month in (3, 4, 5):
        return "SUMMER"
    elif month in (6, 7, 8):
        return "MONSOON"
    else:
        return "POST_MONSOON"

def generate_dataset():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # Initialize customers with category affiliations
    customers = []
    for i in range(1, NUM_CUSTOMERS + 1):
        # 85% domestic customers, 15% commercial customers
        is_comm = (random.random() < 0.12)
        if is_comm:
            cat = "COMMERCIAL_19_0"
        else:
            cat = "DOMESTIC_14_2" if random.random() < 0.82 else "DOMESTIC_5_0"
        customers.append({
            "id": f"SYN-CUST-{1000 + i}",
            "preferred_category": cat,
            "distributor_id": random.choice([1, 2, 3]),
            "last_booking_day": None
        })

    bookings = []
    booking_id_counter = 50001

    for day_offset in range(TOTAL_DAYS):
        current_date = START_DATE + timedelta(days=day_offset)
        dow = current_date.weekday() # 0 = Monday, 6 = Sunday
        is_weekend = 1 if dow in (5, 6) else 0
        month = current_date.month
        season = get_season(month)

        # Seasonal multiplier for domestic (winter boost)
        winter_boost = 1.22 if season == "WINTER" else 1.0

        for cust in customers:
            cat = cust["preferred_category"]
            cfg = CATEGORIES[cat]

            # Check if customer books today
            days_since_last = (day_offset - cust["last_booking_day"]) if cust["last_booking_day"] is not None else 999
            
            # Base probability of booking today
            mean_interval = cfg["interval_mean"]
            if days_since_last < (mean_interval * 0.6):
                continue # Refill too soon
            
            prob = 1.0 / mean_interval
            
            # Day-of-week modulation
            if cat.startswith("DOMESTIC"):
                if is_weekend:
                    prob *= 1.30
                prob *= winter_boost
            else:
                if dow in (1, 2, 3): # Tue, Wed, Thu commercial rush
                    prob *= 1.25
                elif is_weekend:
                    prob *= 0.70

            # Add minor noise
            prob *= random.uniform(0.85, 1.15)

            if random.random() < prob:
                # Booking occurs
                if cat == "COMMERCIAL_19_0":
                    quantity = max(1, int(random.gauss(4.0, 1.5)))
                else:
                    quantity = 2 if random.random() < 0.12 else 1

                bookings.append({
                    "booking_id": booking_id_counter,
                    "booking_date": current_date.strftime("%Y-%m-%d"),
                    "customer_id": cust["id"],
                    "distributor_id": cust["distributor_id"],
                    "cylinder_category": cat,
                    "capacity_kg": cfg["capacity_kg"],
                    "quantity": quantity,
                    "day_of_week": dow,
                    "day_name": current_date.strftime("%A"),
                    "day_of_month": current_date.day,
                    "month": month,
                    "season": season,
                    "is_weekend": is_weekend,
                    "booking_interval_days": min(days_since_last, 90) if days_since_last != 999 else mean_interval,
                    "data_source": "SYNTHETIC_TRAINING_DATA"
                })
                cust["last_booking_day"] = day_offset
                booking_id_counter += 1

    # Write to CSV
    fieldnames = [
        "booking_id", "booking_date", "customer_id", "distributor_id",
        "cylinder_category", "capacity_kg", "quantity",
        "day_of_week", "day_name", "day_of_month", "month", "season",
        "is_weekend", "booking_interval_days", "data_source"
    ]

    with open(OUTPUT_FILE, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(bookings)

    print(f"[SYNTHETIC DATASET GENERATED]")
    print(f"Total simulated bookings: {len(bookings)}")
    print(f"Date range: {START_DATE.strftime('%Y-%m-%d')} to {(START_DATE + timedelta(days=TOTAL_DAYS-1)).strftime('%Y-%m-%d')}")
    print(f"File path: {OUTPUT_FILE}")
    print(f"Random seed: {RANDOM_SEED}")
    return OUTPUT_FILE

if __name__ == "__main__":
    generate_dataset()
