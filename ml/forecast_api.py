"""
forecast_api.py
----------------
Lightweight FastAPI prediction service for LPG Demand Forecasting.

DISCLAIMER:
All forecasts provided by this service are generated by a model trained exclusively
on synthetic, simulated data. These predictions are provided for demonstration and
cold-start demand planning only, and do not represent verified consumer behavior.
"""

import os
os.environ["OPENBLAS_NUM_THREADS"] = "1"
os.environ["MKL_NUM_THREADS"] = "1"
os.environ["OMP_NUM_THREADS"] = "1"
os.environ["NUMEXPR_NUM_THREADS"] = "1"

import json
import pickle
from datetime import datetime, timedelta
from typing import List, Optional
import numpy as np
import pandas as pd
from fastapi import FastAPI, Query, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.join(BASE_DIR, "models")
MODEL_FILE = os.path.join(MODELS_DIR, "demand_forecast_model.pkl")
METRICS_FILE = os.path.join(MODELS_DIR, "evaluation_metrics.json")
METADATA_FILE = os.path.join(MODELS_DIR, "model_metadata.json")
DATA_FILE = os.path.join(BASE_DIR, "data", "synthetic_bookings.csv")

app = FastAPI(
    title="LPG-Chain Demand Forecasting Service",
    description="AI/ML Demand Forecasting API trained on synthetic distribution history",
    version="1.0.0"
)

# Enable CORS for frontend Vite application
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

model = None
metrics_data = {}
metadata = {}

CATEGORY_INFO = {
    "DOMESTIC_14_2": {"name": "Domestic 14.2 kg", "capacity_kg": 14.2, "type": "DOMESTIC"},
    "DOMESTIC_5_0": {"name": "Domestic 5 kg", "capacity_kg": 5.0, "type": "DOMESTIC"},
    "COMMERCIAL_19_0": {"name": "Commercial 19 kg", "capacity_kg": 19.0, "type": "COMMERCIAL"},
}

def load_artifacts():
    global model, metrics_data, metadata
    if os.path.exists(MODEL_FILE):
        with open(MODEL_FILE, "rb") as f:
            model = pickle.load(f)
    if os.path.exists(METRICS_FILE):
        with open(METRICS_FILE, "r", encoding="utf-8") as f:
            metrics_data = json.load(f)
    if os.path.exists(METADATA_FILE):
        with open(METADATA_FILE, "r", encoding="utf-8") as f:
            metadata = json.load(f)

@app.on_event("startup")
def startup_event():
    load_artifacts()

@app.get("/health")
def health_check():
    return {
        "status": "UP",
        "service": "lpg-chain-ai-demand-forecast",
        "model_loaded": model is not None,
        "model_version": metrics_data.get("model_version", "v1.0.0-synthetic-rf"),
        "data_source": "SYNTHETIC_TRAINING_DATA",
        "timestamp": datetime.now().isoformat()
    }

@app.get("/metrics")
def get_metrics():
    if not metrics_data:
        load_artifacts()
    if not metrics_data:
        raise HTTPException(status_code=503, detail="Model metrics artifact not found. Please train the model first.")
    return metrics_data

@app.get("/forecast")
def get_forecast(
    horizon_days: int = Query(7, description="Forecast horizon in days (7, 14, or 30)"),
    distributor_id: Optional[int] = Query(None, description="Distributor agency ID (optional context filter)")
):
    if horizon_days not in (7, 14, 30):
        horizon_days = 7 if horizon_days <= 7 else (14 if horizon_days <= 14 else 30)
        
    if model is None:
        load_artifacts()
    if model is None:
        raise HTTPException(
            status_code=503,
            detail="Forecast model is not loaded. Please run 'python train_forecasting_model.py' to produce model artifacts."
        )

    # Multi-step autoregressive forecasting
    start_date = datetime.now() + timedelta(days=1)
    forecast_dates = [start_date + timedelta(days=i) for i in range(horizon_days)]
    
    categories = ["DOMESTIC_14_2", "DOMESTIC_5_0", "COMMERCIAL_19_0"]
    category_results = []
    daily_aggregates = {d.strftime("%Y-%m-%d"): 0 for d in forecast_dates}
    
    for cat in categories:
        cat_info = CATEGORY_INFO[cat]
        # Seed initial history from typical synthetic series
        # 14.2kg ~ 18-24/day, 5kg ~ 4-8/day, 19kg ~ 6-14/day
        base_qty = 22.0 if cat == "DOMESTIC_14_2" else (6.0 if cat == "DOMESTIC_5_0" else 9.0)
        history = [max(0.0, base_qty + np.sin(i / 3.0) * 3.0) for i in range(40)]
        
        daily_preds = []
        total_qty = 0
        
        for d in forecast_dates:
            dow = d.weekday()
            dom = d.day
            month = d.month
            is_weekend = 1 if dow in (5, 6) else 0
            quarter = (month - 1) // 3 + 1
            
            lag_1 = history[-1]
            lag_7 = history[-7] if len(history) >= 7 else base_qty
            lag_14 = history[-14] if len(history) >= 14 else base_qty
            lag_21 = history[-21] if len(history) >= 21 else base_qty
            lag_28 = history[-28] if len(history) >= 28 else base_qty
            
            rolling_7 = float(np.mean(history[-7:]))
            rolling_std_7 = float(np.std(history[-7:]))
            rolling_14 = float(np.mean(history[-14:]))
            
            feature_row = [
                dow, dom, month, is_weekend, quarter,
                lag_1, lag_7, lag_14, lag_21, lag_28,
                rolling_7, rolling_std_7, rolling_14,
                1 if cat == "DOMESTIC_14_2" else 0,
                1 if cat == "DOMESTIC_5_0" else 0,
                1 if cat == "COMMERCIAL_19_0" else 0
            ]
            
            pred = float(model.predict([feature_row])[0])
            pred = max(0.0, pred)
            
            # Subtle distributor scaling factor if provided
            if distributor_id is not None:
                scale = 0.9 + ((distributor_id % 3) * 0.1)
                pred *= scale
                
            pred_int = int(round(pred))
            history.append(pred)
            total_qty += pred_int
            
            date_str = d.strftime("%Y-%m-%d")
            daily_aggregates[date_str] += pred_int
            
            daily_preds.append({
                "date": date_str,
                "day_name": d.strftime("%a"),
                "predicted_quantity": pred_int,
                "confidence_lower": max(0, int(round(pred * 0.85))),
                "confidence_upper": int(round(pred * 1.15))
            })
            
        category_results.append({
            "cylinder_category": cat,
            "category_display_name": cat_info["name"],
            "capacity_kg": cat_info["capacity_kg"],
            "service_type": cat_info["type"],
            "total_predicted_quantity": total_qty,
            "daily_forecast": daily_preds
        })
        
    daily_summary_list = [
        {"date": d_str, "total_predicted_quantity": q}
        for d_str, q in sorted(daily_aggregates.items())
    ]
    
    return {
        "distributor_id": distributor_id,
        "horizon_days": horizon_days,
        "forecast_generated_at": datetime.now().isoformat(),
        "model_version": metrics_data.get("model_version", "v1.0.0-synthetic-rf"),
        "data_source": "SYNTHETIC_TRAINING_DATA",
        "disclaimer": "Forecast is generated from a synthetic training baseline for initial system demonstration. Not for real operational commitments.",
        "evaluation_metrics": metrics_data.get("overall_metrics", {}),
        "total_predicted_demand": sum(c["total_predicted_quantity"] for c in category_results),
        "category_forecasts": category_results,
        "daily_summary": daily_summary_list
    }

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("forecast_api:app", host="0.0.0.0", port=8000, reload=True)
